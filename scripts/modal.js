// --- Các hàm tiện ích chung (Helper Functions) ---
const toggleBodyScroll = (lock) => {
  document.body.style.overflow = lock ? "hidden" : "";
};

const toggleModalState = (modal, show) => {
  if (!modal) return;
  if (show) {
    modal.classList.remove("hidden");
    modal.classList.add("flex");
    toggleBodyScroll(true);
  } else {
    modal.classList.add("hidden");
    modal.classList.remove("flex");
    toggleBodyScroll(false);
  }
};

// --- Xử lý Map Modal ---
const mapModal = document.getElementById("map-modal");
const mapIframe = document.querySelector(".gmap_iframe");

function openMap() {
  toggleModalState(mapModal, true);
}

function closeMap() {
  toggleModalState(mapModal, false);
}

// Dùng Event Delegation cho các nút xem bản đồ
document.addEventListener("click", (e) => {
  const btn = e.target.closest(".btn-view-map");
  if (btn) {
    e.preventDefault();
    const mapSrc = btn.getAttribute("data-map-src");
    if (mapSrc && mapIframe) {
      mapIframe.src = mapSrc;
    }
    openMap();
  }
});

// --- Xử lý Content Detail Modal ---
const contentModal = document.getElementById("content-modal");
const modalTitle = document.getElementById("modal-content-title");
const modalGallery = document.getElementById("modal-content-gallery");
const modalDesc = document.getElementById("modal-content-desc");

// Gắn vào window để có thể gọi từ HTML (onclick="openContentModal(...)")
window.openContentModal = function (id) {
  const data = contentData[id];
  if (!data) return;

  // 1. Gán nội dung
  modalTitle.textContent = data.title;
  modalDesc.innerHTML = data.desc;

  // 2. Tạo gallery ảnh (Sử dụng Fragment để tối ưu DOM insertion)
  modalGallery.innerHTML = "";
  if (data.images && data.images.length > 0) {
    const fragment = document.createDocumentFragment();
    data.images.forEach((imgSrc) => {
      const imgDiv = document.createElement("div");
      imgDiv.className =
        "rounded-lg overflow-hidden shadow-md h-56 bg-gray-200 group";
      imgDiv.innerHTML = `
        <img src="${imgSrc}" loading="lazy" alt="${data.title}" 
             class="w-full h-full object-cover transition duration-500 group-hover:scale-110 cursor-pointer">
      `;
      fragment.appendChild(imgDiv);
    });
    modalGallery.appendChild(fragment);
  }

  toggleModalState(contentModal, true);
};

window.closeContentModal = function () {
  toggleModalState(contentModal, false);
};

// --- Global Event Listeners ---
// Đóng modal khi nhấn ESC hoặc click ra ngoài backdrop
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") {
    closeContentModal();
    closeMap();
  }
});
